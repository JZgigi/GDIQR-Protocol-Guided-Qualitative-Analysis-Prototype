-- Benchmark v1 foundation: isolated, run-scoped, append-oriented analysis data.
-- This migration deliberately excludes relationship graphs, category hierarchies,
-- production protocol registries, and hard immutability triggers.

create table if not exists public.benchmark_runs (
  id text primary key default ('bench_' || replace(gen_random_uuid()::text, '-', '')),
  run_number bigint generated by default as identity unique,
  project_id text not null references public.projects(id) on delete restrict,
  status text not null default 'running'
    check (status in ('running', 'completed_frozen', 'failed')),
  current_stage text not null default 'mu_draft'
    check (current_stage in (
      'mu_draft', 'mu_review', 'mu_final',
      'category_draft', 'category_review', 'category_final',
      'integration_draft', 'integration_review', 'integration_final',
      'final_validation'
    )),
  research_question text not null,
  study_context text not null,
  analytic_dataset_metadata jsonb not null,
  transcript_snapshot jsonb not null,
  speaker_roles_snapshot jsonb not null,
  transcript_hash text not null,
  translated_transcript_hash text not null,
  methodological_protocol_version text not null,
  methodological_protocol_snapshot jsonb not null,
  methodological_protocol_hash text not null,
  computational_config_version text not null,
  computational_config_snapshot jsonb not null,
  computational_config_hash text not null,
  input_hash text not null,
  application_version text,
  git_commit text,
  failure_summary text,
  final_output_hash text,
  mu_execution_started_at timestamptz,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  frozen_at timestamptz
);

create table if not exists public.benchmark_stage_outputs (
  id text primary key default ('bstage_' || replace(gen_random_uuid()::text, '-', '')),
  run_id text not null references public.benchmark_runs(id) on delete restrict,
  stage text not null check (stage in (
    'mu_draft', 'mu_review', 'mu_final',
    'category_draft', 'category_review', 'category_final',
    'integration_draft', 'integration_review', 'integration_final',
    'final_validation'
  )),
  batch_id text not null,
  stage_sequence integer not null check (stage_sequence > 0),
  status text not null check (status in ('completed', 'failed')),
  schema_version text not null,
  input_reference_hash text not null,
  structured_output jsonb,
  output_hash text,
  validation_result jsonb not null default '{}'::jsonb,
  error text,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (run_id, stage_sequence)
);

create table if not exists public.benchmark_model_attempts (
  id text primary key default ('battempt_' || replace(gen_random_uuid()::text, '-', '')),
  run_id text not null references public.benchmark_runs(id) on delete restrict,
  stage_output_id text references public.benchmark_stage_outputs(id) on delete restrict,
  stage text not null check (stage in (
    'mu_draft', 'mu_review', 'mu_final',
    'category_draft', 'category_review', 'category_final',
    'integration_draft', 'integration_review', 'integration_final'
  )),
  batch_id text not null,
  attempt_number integer not null check (attempt_number > 0),
  attempt_type text not null
    check (attempt_type in ('initial', 'technical_retry', 'json_repair')),
  provider text not null,
  model text not null,
  model_digest text,
  parameter_snapshot jsonb not null,
  prompt_template_version text not null,
  prompt_template_hash text not null,
  request_hash text not null,
  raw_response text,
  parsed_response jsonb,
  validation_status text not null
    check (validation_status in ('valid', 'invalid')),
  failure_category text check (failure_category in (
    'transport_failure', 'timeout', 'malformed_json', 'schema_invalid',
    'invalid_reference', 'semantic_validation_failure'
  )),
  error text,
  duration_ms integer,
  provider_generation_id text,
  provider_response_model text,
  created_at timestamptz not null default now(),
  check (
    (validation_status = 'valid' and failure_category is null) or
    (validation_status = 'invalid' and failure_category is not null)
  ),
  unique (run_id, stage, batch_id, attempt_number)
);

create table if not exists public.benchmark_meaning_units (
  id text primary key default ('bmu_' || replace(gen_random_uuid()::text, '-', '')),
  run_id text not null references public.benchmark_runs(id) on delete restrict,
  mu_id text not null,
  transcript_id text not null,
  focus_group_id text not null,
  speaker_id text not null,
  speaker_role text not null
    check (speaker_role in ('participant', 'facilitator', 'unknown')),
  turn_ids text[] not null default '{}',
  source_start integer check (source_start >= 0),
  source_end integer,
  source_text text not null,
  source_span_hash text not null,
  summary text not null,
  uncertainty text,
  source_draft_mu_ids text[] not null default '{}',
  applied_review_finding_ids text[] not null default '{}',
  review_action text not null
    check (review_action in ('unchanged', 'revised', 'split', 'merged', 'added')),
  sort_order integer not null,
  created_at timestamptz not null default now(),
  check (
    (source_start is null and source_end is null) or
    (source_start is not null and source_end is not null and source_end >= source_start)
  ),
  unique (run_id, mu_id)
);

create table if not exists public.benchmark_categories (
  id text primary key default ('bcat_' || replace(gen_random_uuid()::text, '-', '')),
  run_id text not null references public.benchmark_runs(id) on delete restrict,
  category_id text not null,
  name text not null,
  description text not null,
  rationale text not null,
  source_draft_category_ids text[] not null default '{}',
  applied_review_finding_ids text[] not null default '{}',
  sort_order integer not null,
  created_at timestamptz not null default now(),
  unique (run_id, category_id)
);

create table if not exists public.benchmark_category_memberships (
  run_id text not null references public.benchmark_runs(id) on delete restrict,
  category_id text not null,
  meaning_unit_id text not null,
  created_at timestamptz not null default now(),
  primary key (run_id, category_id, meaning_unit_id),
  foreign key (run_id, category_id)
    references public.benchmark_categories(run_id, category_id) on delete restrict,
  foreign key (run_id, meaning_unit_id)
    references public.benchmark_meaning_units(run_id, mu_id) on delete restrict
);

create table if not exists public.benchmark_integrated_narratives (
  id text primary key default ('bintegration_' || replace(gen_random_uuid()::text, '-', '')),
  run_id text not null unique references public.benchmark_runs(id) on delete restrict,
  narrative text not null,
  claims jsonb not null default '[]'::jsonb,
  applied_review_finding_ids text[] not null default '{}',
  evidence_validation jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists benchmark_stage_outputs_run_sequence_idx
  on public.benchmark_stage_outputs(run_id, stage_sequence);
create index if not exists benchmark_model_attempts_run_stage_idx
  on public.benchmark_model_attempts(run_id, stage, batch_id, attempt_number);
create index if not exists benchmark_meaning_units_run_sort_idx
  on public.benchmark_meaning_units(run_id, sort_order);
create index if not exists benchmark_categories_run_sort_idx
  on public.benchmark_categories(run_id, sort_order);

alter table public.benchmark_runs enable row level security;
alter table public.benchmark_stage_outputs enable row level security;
alter table public.benchmark_model_attempts enable row level security;
alter table public.benchmark_meaning_units enable row level security;
alter table public.benchmark_categories enable row level security;
alter table public.benchmark_category_memberships enable row level security;
alter table public.benchmark_integrated_narratives enable row level security;

revoke all on
  public.benchmark_runs,
  public.benchmark_stage_outputs,
  public.benchmark_model_attempts,
  public.benchmark_meaning_units,
  public.benchmark_categories,
  public.benchmark_category_memberships,
  public.benchmark_integrated_narratives
from anon, authenticated;

grant select, insert, update on public.benchmark_runs to service_role;
grant select, insert on
  public.benchmark_stage_outputs,
  public.benchmark_model_attempts,
  public.benchmark_meaning_units,
  public.benchmark_categories,
  public.benchmark_category_memberships,
  public.benchmark_integrated_narratives
to service_role;

grant usage, select on sequence public.benchmark_runs_run_number_seq to service_role;
